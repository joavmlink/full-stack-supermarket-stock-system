#!/usr/bin/env node
// Generates backend/src/lib/password-blocklist-data.ts from a SecLists password
// list (MIT license). Only entries the password policy could accept are kept:
// shorter ones are already rejected by the minimum length.
// Usage: node scripts/build-password-blocklist.mjs <path-to-list.txt>
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { basename, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

export const MIN_LENGTH = 15;
export const MAX_LENGTH = 128;
const OUTPUT = 'backend/src/lib/password-blocklist-data.ts';
const SOURCE_URL =
  'https://github.com/danielmiessler/SecLists/blob/master/Passwords/Common-Credentials/100k-most-used-passwords-NCSC.txt';

const HASHCAT_HEX = /^\$hex\[([0-9a-f]+)\]$/i;

/** Lists encode passwords with unusual bytes in hashcat's `$hex[...]` notation. */
function decodeLine(line) {
  const match = HASHCAT_HEX.exec(line);
  return match ? Buffer.from(match[1], 'hex').toString('utf8') : line;
}

/** An entry that is an email address: someone's personal data, which has no place in the repository. */
const EMAIL = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

/** Normalizes like the password policy (NFC, lowercase) and keeps unique entries within the length limits, without emails. */
export function selectEntries(text) {
  const entries = new Set();
  for (const line of text.split(/\r?\n/)) {
    const entry = decodeLine(line).normalize('NFC').toLowerCase();
    const length = [...entry].length;
    if (length >= MIN_LENGTH && length <= MAX_LENGTH && !EMAIL.test(entry)) entries.add(entry);
  }
  return [...entries].sort();
}

export function renderModule(entries, { sourceName, sha256 }) {
  return `// Generated by scripts/build-password-blocklist.mjs. Do not edit by hand.
// Source: ${SOURCE_URL}
// File: ${sourceName} (sha256 ${sha256})
// SecLists, MIT License, Copyright (c) 2018 Daniel Miessler.
// Entries are NFC-normalized, lowercased, limited to ${MIN_LENGTH}-${MAX_LENGTH} characters and without email addresses.
export const COMMON_PASSWORDS: readonly string[] = ${JSON.stringify(entries, null, 2)};
`;
}

if (import.meta.url === pathToFileURL(resolve(process.argv[1] ?? '')).href) {
  const input = process.argv[2];
  if (!input) {
    console.error('Usage: node scripts/build-password-blocklist.mjs <path-to-list.txt>');
    process.exit(1);
  }
  const raw = readFileSync(input);
  const entries = selectEntries(raw.toString('utf8'));
  const sha256 = createHash('sha256').update(raw).digest('hex');
  writeFileSync(OUTPUT, renderModule(entries, { sourceName: basename(input), sha256 }));
  console.log(`✓ Wrote ${entries.length} entries to ${OUTPUT}`);
}
